-- QueryForge metadata schema, version 2: report parameters, enterprise identities,
-- groups, report sharing, scheduled runs and the scheduler lease.
-- {{SCHEMA}} is replaced with META_SCHEMA by scripts/migrate.ts. All timestamps are UTC.

-- Report parameter definitions (JSON array, validated by the server before it is stored).
ALTER TABLE {{SCHEMA}}.QF_REPORTS ADD COLUMN PARAMETERS_JSON CLOB(64K) CCSID 1208;

-- Execution history: parameter values used, and the schedule that triggered the run.
ALTER TABLE {{SCHEMA}}.QF_EXECUTIONS ADD COLUMN PARAMS_JSON VARCHAR(8000) CCSID 1208;

ALTER TABLE {{SCHEMA}}.QF_EXECUTIONS ADD COLUMN SCHEDULE_ID VARCHAR(36);

ALTER TABLE {{SCHEMA}}.QF_EXECUTIONS DROP CONSTRAINT QF_EXEC_CK_KIND;

ALTER TABLE {{SCHEMA}}.QF_EXECUTIONS ADD CONSTRAINT QF_EXEC_CK_KIND CHECK (KIND IN ('RUN', 'EXPORT', 'SCHEDULE'));

-- Enterprise identities. External accounts store '!' as PASSWORD_HASH, which can never match bcrypt.
ALTER TABLE {{SCHEMA}}.QF_USERS ADD COLUMN AUTH_SOURCE VARCHAR(8) NOT NULL DEFAULT 'LOCAL';

ALTER TABLE {{SCHEMA}}.QF_USERS ADD COLUMN EXTERNAL_ID VARCHAR(512);

ALTER TABLE {{SCHEMA}}.QF_USERS ADD COLUMN EMAIL VARCHAR(320);

ALTER TABLE {{SCHEMA}}.QF_USERS ADD CONSTRAINT QF_USERS_CK_SOURCE CHECK (AUTH_SOURCE IN ('LOCAL', 'OIDC', 'LDAP'));

CREATE UNIQUE WHERE NOT NULL INDEX {{SCHEMA}}.QF_USERS_UX_EXTERNAL ON {{SCHEMA}}.QF_USERS (AUTH_SOURCE, EXTERNAL_ID);

-- Application group membership (mapped from IdP / directory groups at sign-in, or assigned locally).
CREATE TABLE {{SCHEMA}}.QF_USER_GROUPS (
  USER_ID     VARCHAR(36)  NOT NULL,
  GROUP_NAME  VARCHAR(128) NOT NULL,
  SOURCE      VARCHAR(8)   NOT NULL DEFAULT 'LOCAL',
  CREATED_AT  TIMESTAMP    NOT NULL,
  CONSTRAINT QF_UGRP_PK PRIMARY KEY (USER_ID, GROUP_NAME),
  CONSTRAINT QF_UGRP_FK_USER FOREIGN KEY (USER_ID) REFERENCES {{SCHEMA}}.QF_USERS (USER_ID) ON DELETE CASCADE,
  CONSTRAINT QF_UGRP_CK_SOURCE CHECK (SOURCE IN ('LOCAL', 'OIDC', 'LDAP'))
);

CREATE INDEX {{SCHEMA}}.QF_UGRP_IX_GROUP ON {{SCHEMA}}.QF_USER_GROUPS (GROUP_NAME);

-- Report sharing: a user or an application group gets VIEWER (run/export) or EDITOR access.
CREATE TABLE {{SCHEMA}}.QF_REPORT_SHARES (
  REPORT_ID       VARCHAR(36)  NOT NULL,
  PRINCIPAL_TYPE  VARCHAR(8)   NOT NULL,
  PRINCIPAL_ID    VARCHAR(128) NOT NULL,
  SHARE_ROLE      VARCHAR(8)   NOT NULL,
  CREATED_BY      VARCHAR(36)  NOT NULL,
  CREATED_AT      TIMESTAMP    NOT NULL,
  CONSTRAINT QF_SHARE_PK PRIMARY KEY (REPORT_ID, PRINCIPAL_TYPE, PRINCIPAL_ID),
  CONSTRAINT QF_SHARE_FK_REPORT FOREIGN KEY (REPORT_ID) REFERENCES {{SCHEMA}}.QF_REPORTS (REPORT_ID) ON DELETE CASCADE,
  CONSTRAINT QF_SHARE_CK_TYPE CHECK (PRINCIPAL_TYPE IN ('USER', 'GROUP')),
  CONSTRAINT QF_SHARE_CK_ROLE CHECK (SHARE_ROLE IN ('VIEWER', 'EDITOR'))
);

CREATE INDEX {{SCHEMA}}.QF_SHARE_IX_PRINCIPAL ON {{SCHEMA}}.QF_REPORT_SHARES (PRINCIPAL_TYPE, PRINCIPAL_ID);

-- Scheduled runs. Each run executes as the report owner and emails the XLSX to RECIPIENTS.
CREATE TABLE {{SCHEMA}}.QF_SCHEDULES (
  SCHEDULE_ID       VARCHAR(36)   NOT NULL,
  REPORT_ID         VARCHAR(36)   NOT NULL,
  CREATED_BY        VARCHAR(36)   NOT NULL,
  CRON_EXPR         VARCHAR(128)  NOT NULL,
  TIMEZONE          VARCHAR(64)   NOT NULL,
  RECIPIENTS        VARCHAR(4000) NOT NULL,
  PARAMS_JSON       VARCHAR(8000) CCSID 1208,
  IS_ENABLED        SMALLINT      NOT NULL DEFAULT 1,
  NEXT_RUN_AT       TIMESTAMP,
  LAST_RUN_AT       TIMESTAMP,
  LAST_STATUS       VARCHAR(16)   NOT NULL DEFAULT 'NEVER',
  LAST_ERROR        VARCHAR(1000),
  FAILURE_COUNT     INTEGER       NOT NULL DEFAULT 0,
  VERSION           INTEGER       NOT NULL DEFAULT 1,
  CREATED_AT        TIMESTAMP     NOT NULL,
  UPDATED_AT        TIMESTAMP     NOT NULL,
  CONSTRAINT QF_SCHED_PK PRIMARY KEY (SCHEDULE_ID),
  CONSTRAINT QF_SCHED_FK_REPORT FOREIGN KEY (REPORT_ID) REFERENCES {{SCHEMA}}.QF_REPORTS (REPORT_ID) ON DELETE CASCADE,
  CONSTRAINT QF_SCHED_CK_ENABLED CHECK (IS_ENABLED IN (0, 1)),
  CONSTRAINT QF_SCHED_CK_STATUS CHECK (LAST_STATUS IN ('NEVER', 'RUNNING', 'SUCCEEDED', 'FAILED'))
);

CREATE INDEX {{SCHEMA}}.QF_SCHED_IX_DUE ON {{SCHEMA}}.QF_SCHEDULES (IS_ENABLED, NEXT_RUN_AT);

CREATE INDEX {{SCHEMA}}.QF_SCHED_IX_REPORT ON {{SCHEMA}}.QF_SCHEDULES (REPORT_ID);

-- Cluster-wide leases. The scheduler holds LOCK_NAME = 'SCHEDULER' so only one instance runs schedules.
CREATE TABLE {{SCHEMA}}.QF_LOCKS (
  LOCK_NAME   VARCHAR(64)  NOT NULL,
  HOLDER      VARCHAR(128) NOT NULL,
  EXPIRES_AT  TIMESTAMP    NOT NULL,
  CONSTRAINT QF_LOCKS_PK PRIMARY KEY (LOCK_NAME)
);

LABEL ON TABLE {{SCHEMA}}.QF_USER_GROUPS IS 'QueryForge application group membership';

LABEL ON TABLE {{SCHEMA}}.QF_REPORT_SHARES IS 'QueryForge report sharing';

LABEL ON TABLE {{SCHEMA}}.QF_SCHEDULES IS 'QueryForge scheduled report runs';

LABEL ON TABLE {{SCHEMA}}.QF_LOCKS IS 'QueryForge scheduler leases';
