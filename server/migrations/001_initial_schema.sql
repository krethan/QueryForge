-- QueryForge / IBM i Query Reports metadata schema, version 1
-- {{SCHEMA}} is replaced with META_SCHEMA (validated identifier) by scripts/migrate.ts.
-- All timestamps are stored in UTC.

CREATE TABLE {{SCHEMA}}.QF_USERS (
  USER_ID        VARCHAR(36)   NOT NULL,
  USERNAME       VARCHAR(128)  NOT NULL,
  DISPLAY_NAME   VARCHAR(256)  NOT NULL,
  PASSWORD_HASH  VARCHAR(128)  NOT NULL,
  ROLE           VARCHAR(16)   NOT NULL DEFAULT 'USER',
  IS_ACTIVE      SMALLINT      NOT NULL DEFAULT 1,
  FAILED_LOGINS  INTEGER       NOT NULL DEFAULT 0,
  LOCKED_UNTIL   TIMESTAMP,
  LAST_LOGIN_AT  TIMESTAMP,
  CREATED_AT     TIMESTAMP     NOT NULL,
  UPDATED_AT     TIMESTAMP     NOT NULL,
  CONSTRAINT QF_USERS_PK PRIMARY KEY (USER_ID),
  CONSTRAINT QF_USERS_UK_NAME UNIQUE (USERNAME),
  CONSTRAINT QF_USERS_CK_ROLE CHECK (ROLE IN ('USER', 'ADMIN')),
  CONSTRAINT QF_USERS_CK_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
  CONSTRAINT QF_USERS_CK_NAME CHECK (LENGTH(TRIM(USERNAME)) > 0)
);

CREATE TABLE {{SCHEMA}}.QF_REPORTS (
  REPORT_ID         VARCHAR(36)    NOT NULL,
  OWNER_ID          VARCHAR(36)    NOT NULL,
  REPORT_NAME       VARCHAR(128)   NOT NULL,
  REPORT_NAME_KEY   VARCHAR(128)   NOT NULL,
  DESCRIPTION       VARCHAR(2000),
  CATEGORY          VARCHAR(128),
  SQL_TEXT          CLOB(1M) CCSID 1208 NOT NULL,
  VERSION           INTEGER        NOT NULL DEFAULT 1,
  CREATED_AT        TIMESTAMP      NOT NULL,
  UPDATED_AT        TIMESTAMP      NOT NULL,
  LAST_EXECUTED_AT  TIMESTAMP,
  LAST_STATUS       VARCHAR(16)    NOT NULL DEFAULT 'NEVER',
  LAST_ROW_COUNT    INTEGER,
  LAST_DURATION_MS  INTEGER,
  CONSTRAINT QF_REPORTS_PK PRIMARY KEY (REPORT_ID),
  CONSTRAINT QF_REPORTS_FK_OWNER FOREIGN KEY (OWNER_ID) REFERENCES {{SCHEMA}}.QF_USERS (USER_ID) ON DELETE RESTRICT,
  CONSTRAINT QF_REPORTS_UK_NAME UNIQUE (OWNER_ID, REPORT_NAME_KEY),
  CONSTRAINT QF_REPORTS_CK_NAME CHECK (LENGTH(TRIM(REPORT_NAME)) > 0),
  CONSTRAINT QF_REPORTS_CK_STATUS CHECK (LAST_STATUS IN ('NEVER', 'RUNNING', 'SUCCEEDED', 'FAILED', 'TIMED_OUT', 'CANCELLED'))
);

CREATE INDEX {{SCHEMA}}.QF_REPORTS_IX_OWNER_EXEC ON {{SCHEMA}}.QF_REPORTS (OWNER_ID, LAST_EXECUTED_AT DESC);

CREATE INDEX {{SCHEMA}}.QF_REPORTS_IX_OWNER_CAT ON {{SCHEMA}}.QF_REPORTS (OWNER_ID, CATEGORY);

CREATE INDEX {{SCHEMA}}.QF_REPORTS_IX_OWNER_CRT ON {{SCHEMA}}.QF_REPORTS (OWNER_ID, CREATED_AT DESC);

CREATE TABLE {{SCHEMA}}.QF_EXECUTIONS (
  EXECUTION_ID   VARCHAR(36)   NOT NULL,
  REPORT_ID      VARCHAR(36),
  USER_ID        VARCHAR(36)   NOT NULL,
  KIND           VARCHAR(8)    NOT NULL DEFAULT 'RUN',
  STATUS         VARCHAR(16)   NOT NULL,
  STARTED_AT     TIMESTAMP     NOT NULL,
  COMPLETED_AT   TIMESTAMP,
  ELAPSED_MS     INTEGER,
  ROW_COUNT      INTEGER,
  TRUNCATED      SMALLINT      NOT NULL DEFAULT 0,
  SQL_STATE      CHAR(5),
  SQL_CODE       INTEGER,
  ERROR_MESSAGE  VARCHAR(1000),
  SQL_SHA256     CHAR(64)      NOT NULL,
  CONSTRAINT QF_EXEC_PK PRIMARY KEY (EXECUTION_ID),
  CONSTRAINT QF_EXEC_FK_REPORT FOREIGN KEY (REPORT_ID) REFERENCES {{SCHEMA}}.QF_REPORTS (REPORT_ID) ON DELETE SET NULL,
  CONSTRAINT QF_EXEC_FK_USER FOREIGN KEY (USER_ID) REFERENCES {{SCHEMA}}.QF_USERS (USER_ID) ON DELETE RESTRICT,
  CONSTRAINT QF_EXEC_CK_KIND CHECK (KIND IN ('RUN', 'EXPORT')),
  CONSTRAINT QF_EXEC_CK_STATUS CHECK (STATUS IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'TIMED_OUT', 'CANCELLED')),
  CONSTRAINT QF_EXEC_CK_TRUNC CHECK (TRUNCATED IN (0, 1))
);

CREATE INDEX {{SCHEMA}}.QF_EXEC_IX_USER ON {{SCHEMA}}.QF_EXECUTIONS (USER_ID, STARTED_AT DESC);

CREATE INDEX {{SCHEMA}}.QF_EXEC_IX_REPORT ON {{SCHEMA}}.QF_EXECUTIONS (REPORT_ID, STARTED_AT DESC);

LABEL ON TABLE {{SCHEMA}}.QF_USERS IS 'QueryForge application users';

LABEL ON TABLE {{SCHEMA}}.QF_REPORTS IS 'QueryForge saved report definitions';

LABEL ON TABLE {{SCHEMA}}.QF_EXECUTIONS IS 'QueryForge report execution history';
