import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:3079';
const out = process.argv[3] ?? '/home/swilliams/qf-shots/sharing';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const shot = async (name, fullPage = true) => {
  await page.waitForTimeout(600);
  await page.screenshot({ path: `${out}/${name}.png`, fullPage });
  console.log(`${out}/${name}.png`);
};
await page.goto(`${base}/login`);
await page.getByLabel('Username').fill('demo');
await page.getByLabel('Password', { exact: true }).fill('demo-password-123');
await page.getByRole('button', { name: /sign in/i }).click();
await page.getByText('Open Orders by Region').first().waitFor();
await shot('v15-sharing-dashboard-roles');
await page.getByRole('button', { name: 'Share Customer Credit Limits' }).click();
await page.getByRole('dialog').waitFor();
await page.getByText('Pat Analyst (fake)', { exact: true }).waitFor();
await shot('v15-sharing-owner-dialog');
await page.getByRole('button', { name: 'Close', exact: true }).click();
await page.goto(`${base}/reports`);
await page.waitForURL('**/reports');
await page.getByRole('heading', { name: 'Saved Reports', exact: true }).waitFor();
await page.getByRole('button', { name: 'Actions for Customer Credit Limits' }).click();
await page.getByRole('menuitem', { name: 'Access and audit' }).click();
await page.getByRole('dialog').waitFor();
await shot('v15-sharing-access-audit');
await page.getByRole('button', { name: 'Close', exact: true }).click();
await page.goto(`${base}/reports`);
await page.getByText('Regional Pipeline (Pat)', { exact: true }).waitFor();
await page.locator('tr').filter({ hasText: 'Regional Pipeline (Pat)' }).scrollIntoViewIfNeeded();
await shot('v15-sharing-admin-index');
await page.getByRole('button', { name: 'Sign out', exact: true }).click();
await page.getByLabel('Username').fill('pat');
await page.getByLabel('Password', { exact: true }).fill('pat-demo-password');
await page.getByRole('button', { name: /sign in/i }).click();
await page.getByText('Customer Credit Limits', { exact: true }).first().waitFor();
await shot('v15-sharing-recipient-dashboard');
await browser.close();
